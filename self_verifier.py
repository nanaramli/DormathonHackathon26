"""
self_verifier.py - Independent self-verification engine for RichBuddy.

After analysis and file generation, this module verifies:

Input checks:
    - Files can be opened
    - Required columns exist
    - Data types and important values are valid
    - Missing values, duplicates, and cleaning decisions are documented

Calculation checks:
    - Key financial totals are independently recalculated
    - Profit, margins, and totals are mathematically correct
    - Product and category totals reconcile with underlying data

Recommendation checks:
    - Every recommendation links to an actual finding
    - Supporting figures match the computed results
    - Estimates are distinguished from measured results
    - Unsupported conclusions are rejected or marked as hypotheses

Artifact checks:
    - All expected files exist and are non-empty
    - CSV and JSON files can be reopened and parsed
    - Reports contain the required sections
    - Important reported figures match the analysis

Never declares complete success if a critical verification check failed.
"""

import csv
import json
import os
from typing import Any

# Verification status constants
STATUS_PASS = "PASS"
STATUS_FAIL = "FAIL"
STATUS_WARNING = "WARNING"
STATUS_SKIP = "SKIP"

# Severity levels
SEV_CRITICAL = "critical"
SEV_WARNING = "warning"
SEV_INFO = "info"


def run_verification(
    result: dict[str, Any],
    dataset: dict[str, Any],
    output_files: list[str],
) -> dict[str, Any]:
    """Run the full self-verification suite.

    Args:
        result: The orchestrator result dict (contains findings, actions, etc.)
        dataset: The loaded dataset dict (invoices + transactions)
        output_files: List of file paths generated by the pipeline

    Returns:
        A verification report dict with:
            - checks: list of individual check results
            - summary: aggregate pass/fail/warning counts
            - overall_status: "PASS" | "PARTIAL" | "FAIL"
            - errors: list of critical failures
            - warnings: list of non-critical issues
    """
    checks: list[dict[str, Any]] = []

    invoices = dataset.get("invoices", [])
    transactions = dataset.get("transactions", [])
    findings = result.get("findings", {})

    # ==================================================================
    # 1. INPUT CHECKS
    # ==================================================================

    # 1a. Verify files can be opened (data loaded)
    checks.append(_check(
        "input_data_loaded",
        "Input data was loaded successfully",
        len(invoices) > 0 or len(transactions) > 0,
        SEV_CRITICAL,
        f"{len(invoices)} invoices, {len(transactions)} transactions loaded",
    ))

    # 1b. Verify required columns exist
    required_inv_fields = {"invoice_id", "invoice_amount_rm", "status"}
    required_txn_fields = {"type", "amount_rm", "category"}

    inv_cols_ok = True
    if invoices:
        inv_keys = set(invoices[0].keys())
        missing_inv = required_inv_fields - inv_keys
        if missing_inv:
            inv_cols_ok = False
    else:
        missing_inv = set()

    checks.append(_check(
        "input_invoice_columns",
        "Invoice data has required columns",
        inv_cols_ok,
        SEV_WARNING,
        f"Missing: {missing_inv}" if missing_inv else "All required columns present",
    ))

    txn_cols_ok = True
    missing_txn = set()
    if transactions:
        txn_keys = set(transactions[0].keys())
        missing_txn = required_txn_fields - txn_keys
        if missing_txn:
            txn_cols_ok = False

    checks.append(_check(
        "input_transaction_columns",
        "Transaction data has required columns",
        txn_cols_ok,
        SEV_WARNING,
        f"Missing: {missing_txn}" if missing_txn else "All required columns present",
    ))

    # 1c. Check for duplicate invoice IDs
    inv_ids = [inv.get("invoice_id", "") for inv in invoices]
    dup_inv_ids = set([iid for iid in inv_ids if inv_ids.count(iid) > 1])
    checks.append(_check(
        "input_duplicate_invoices",
        "No duplicate invoice IDs",
        len(dup_inv_ids) == 0,
        SEV_WARNING,
        f"{len(dup_inv_ids)} duplicate(s) found: {dup_inv_ids}" if dup_inv_ids else "No duplicates",
    ))

    # 1d. Check for negative amounts in transactions
    neg_txns = [tx for tx in transactions if tx.get("amount_rm", 0) < 0]
    checks.append(_check(
        "input_negative_amounts",
        "No negative transaction amounts",
        len(neg_txns) == 0,
        SEV_WARNING,
        f"{len(neg_txns)} negative amount(s) found" if neg_txns else "All amounts non-negative",
    ))

    # ==================================================================
    # 2. CALCULATION CHECKS
    # ==================================================================

    # 2a. Independently recalculate total revenue
    np = findings.get("net_profit")
    if np and transactions:
        expected_revenue = round(sum(
            tx["amount_rm"] for tx in transactions
            if tx.get("type") == "income"
        ), 2)
        reported_revenue = round(np.get("total_revenue", 0), 2)
        rev_match = abs(expected_revenue - reported_revenue) < 0.01
        checks.append(_check(
            "calc_revenue_total",
            "Total revenue matches independent recalculation",
            rev_match,
            SEV_CRITICAL,
            f"Reported: RM{reported_revenue}, Independently calculated: RM{expected_revenue}",
        ))

        # 2b. Independently recalculate total expenses
        expected_expenses = round(sum(
            tx["amount_rm"] for tx in transactions
            if tx.get("type") == "expense"
        ), 2)
        reported_expenses = round(np.get("total_expenses", 0), 2)
        exp_match = abs(expected_expenses - reported_expenses) < 0.01
        checks.append(_check(
            "calc_expense_total",
            "Total expenses match independent recalculation",
            exp_match,
            SEV_CRITICAL,
            f"Reported: RM{reported_expenses}, Independently calculated: RM{expected_expenses}",
        ))

        # 2c. Verify net profit = revenue - expenses
        expected_net = round(expected_revenue - expected_expenses, 2)
        reported_net = round(np.get("net_profit", 0), 2)
        net_match = abs(expected_net - reported_net) < 0.01
        checks.append(_check(
            "calc_net_profit",
            "Net profit equals revenue minus expenses",
            net_match,
            SEV_CRITICAL,
            f"Reported: RM{reported_net}, Expected: RM{expected_net}",
        ))

        # 2d. Verify profit margin calculation
        if expected_revenue > 0:
            expected_margin = round((expected_net / expected_revenue) * 100, 1)
            reported_margin = round(np.get("profit_margin_pct", 0), 1)
            margin_match = abs(expected_margin - reported_margin) < 0.1
            checks.append(_check(
                "calc_profit_margin",
                "Profit margin is mathematically correct",
                margin_match,
                SEV_CRITICAL,
                f"Reported: {reported_margin}%, Calculated: {expected_margin}%",
            ))
    else:
        checks.append(_check(
            "calc_financial_totals",
            "Financial totals verified",
            False,
            SEV_INFO,
            "No net_profit finding available for verification",
        ))

    # 2e. Verify category totals reconcile
    cat_summary = findings.get("category_summary")
    rev_by_cat = findings.get("revenue_by_category")
    if cat_summary and rev_by_cat and transactions:
        # Sum income from category_summary
        cat_total_income = round(sum(
            c.get("income_rm", 0) for c in cat_summary
        ), 2)
        # Sum from revenue_by_category
        rev_total = round(rev_by_cat.get("total_revenue", 0), 2)
        cat_reconciled = abs(cat_total_income - rev_total) < 0.01
        checks.append(_check(
            "calc_category_reconciliation",
            "Category income totals reconcile with revenue total",
            cat_reconciled,
            SEV_WARNING,
            f"Category sum: RM{cat_total_income}, Revenue total: RM{rev_total}",
        ))
    else:
        checks.append(_check(
            "calc_category_reconciliation",
            "Category totals reconciliation check",
            True,
            SEV_INFO,
            "Skipped - category_summary or revenue_by_category not available",
        ))

    # 2f. Check for zero denominators
    if np and np.get("total_revenue", 0) == 0:
        checks.append(_check(
            "calc_zero_denominator",
            "No zero-denominator division errors",
            False,
            SEV_CRITICAL,
            "Total revenue is zero - profit margin calculation would divide by zero",
        ))
    else:
        checks.append(_check(
            "calc_zero_denominator",
            "No zero-denominator division errors",
            True,
            SEV_INFO,
            "Total revenue is non-zero",
        ))

    # ==================================================================
    # 3. RECOMMENDATION CHECKS
    # ==================================================================

    actions = result.get("actions", [])
    actions_ok = True
    action_errors = []

    for i, action in enumerate(actions):
        # 3a. Each action must have required fields
        required_fields = ["priority", "title", "finding", "recommendation", "rationale", "data_source"]
        missing = [f for f in required_fields if f not in action or not action[f]]
        if missing:
            actions_ok = False
            action_errors.append(f"Action {i+1} missing fields: {missing}")

        # 3b. Priority must be 1, 2, or 3
        if action.get("priority") not in [1, 2, 3]:
            actions_ok = False
            action_errors.append(f"Action {i+1} has invalid priority: {action.get('priority')}")

        # 3c. Finding must contain actual figures (RM or %)
        finding_text = action.get("finding", "")
        has_figure = "RM" in finding_text or "%" in finding_text or "RM " in finding_text
        if not has_figure and action.get("data_source") != "data_quality":
            action_errors.append(f"Action {i+1} finding lacks supporting figures")

    checks.append(_check(
        "rec_structure",
        "All recommendations have required structure",
        actions_ok,
        SEV_CRITICAL,
        "; ".join(action_errors) if action_errors else f"All {len(actions)} recommendation(s) structurally valid",
    ))

    # 3d. Recommendations should be traceable to findings
    finding_sources = set(findings.keys())
    traceable = 0
    untraceable = []
    for action in actions:
        src = action.get("data_source", "")
        # Map data_source to finding keys
        if "outstanding" in src and "outstanding" in finding_sources:
            traceable += 1
        elif "expense" in src and ("expense_ratio" in finding_sources or "expense_by_category" in finding_sources):
            traceable += 1
        elif "revenue_concentration" in src and "revenue_concentration" in finding_sources:
            traceable += 1
        elif "profit" in src and "profit_by_category" in finding_sources:
            traceable += 1
        elif "reconciliation" in src and "reconciliation" in finding_sources:
            traceable += 1
        elif "monthly" in src and "monthly_trends" in finding_sources:
            traceable += 1
        elif "net_profit" in src and "net_profit" in finding_sources:
            traceable += 1
        elif "invoice_status" in src and "invoice_status" in finding_sources:
            traceable += 1
        elif "regional" in src and "regional_analysis" in finding_sources:
            traceable += 1
        elif "data_quality" in src:
            traceable += 1
        else:
            untraceable.append(action.get("title", "Unknown"))

    checks.append(_check(
        "rec_traceability",
        "Recommendations are traceable to analysis findings",
        len(untraceable) == 0,
        SEV_WARNING,
        f"{traceable}/{len(actions)} traceable" + (f". Untraceable: {untraceable}" if untraceable else ""),
    ))

    # ==================================================================
    # 4. ARTIFACT CHECKS
    # ==================================================================

    # 4a. All expected files exist and are non-empty
    expected_extensions = {".txt", ".csv", ".md", ".json"}
    for fpath in output_files:
        fname = os.path.basename(fpath)
        exists = os.path.isfile(fpath)
        size = os.path.getsize(fpath) if exists else 0
        ext = os.path.splitext(fpath)[1].lower()

        checks.append(_check(
            f"artifact_exists_{fname}",
            f"Output file '{fname}' exists and is non-empty",
            exists and size > 0,
            SEV_CRITICAL,
            f"Size: {size} bytes" if exists else "File not found",
        ))

        # 4b. CSV files can be reopened and parsed
        if ext == ".csv" and exists and size > 0:
            try:
                with open(fpath, "r", encoding="utf-8") as f:
                    reader = csv.reader(f)
                    rows = list(reader)
                csv_ok = len(rows) > 1  # at least header + 1 data row
                checks.append(_check(
                    f"artifact_csv_parse_{fname}",
                    f"CSV file '{fname}' can be reopened and parsed",
                    csv_ok,
                    SEV_WARNING,
                    f"{len(rows)} rows (including header)",
                ))
            except Exception as e:
                checks.append(_check(
                    f"artifact_csv_parse_{fname}",
                    f"CSV file '{fname}' can be reopened and parsed",
                    False,
                    SEV_CRITICAL,
                    f"Parse error: {e}",
                ))

        # 4c. JSON files can be reopened and parsed
        if ext == ".json" and exists and size > 0:
            try:
                with open(fpath, "r", encoding="utf-8") as f:
                    data = json.load(f)
                json_ok = isinstance(data, dict) or isinstance(data, list)
                checks.append(_check(
                    f"artifact_json_parse_{fname}",
                    f"JSON file '{fname}' can be reopened and parsed",
                    json_ok,
                    SEV_CRITICAL,
                    f"Valid JSON with {len(data) if isinstance(data, (list, dict)) else 'N/A'} top-level items",
                ))
            except Exception as e:
                checks.append(_check(
                    f"artifact_json_parse_{fname}",
                    f"JSON file '{fname}' can be reopened and parsed",
                    False,
                    SEV_CRITICAL,
                    f"Parse error: {e}",
                ))

        # 4d. Text/Markdown files can be reopened
        if ext in (".txt", ".md") and exists and size > 0:
            try:
                with open(fpath, "r", encoding="utf-8") as f:
                    content = f.read()
                # Check for required sections in report files
                if fname.startswith("business_action_report"):
                    required_sections = ["instruction", "finding", "recommendation", "verification"]
                    missing_sections = [s for s in required_sections if s.lower() not in content.lower()]
                    checks.append(_check(
                        f"artifact_report_sections_{fname}",
                        f"Report '{fname}' contains required sections",
                        len(missing_sections) == 0,
                        SEV_WARNING,
                        f"Missing sections: {missing_sections}" if missing_sections else "All sections present",
                    ))
            except Exception as e:
                checks.append(_check(
                    f"artifact_text_read_{fname}",
                    f"Text file '{fname}' can be reopened",
                    False,
                    SEV_CRITICAL,
                    f"Read error: {e}",
                ))

    # ==================================================================
    # Build summary
    # ==================================================================
    critical_fails = [c for c in checks if c["status"] == STATUS_FAIL and c["severity"] == SEV_CRITICAL]
    warning_fails = [c for c in checks if c["status"] == STATUS_FAIL and c["severity"] == SEV_WARNING]
    passes = [c for c in checks if c["status"] == STATUS_PASS]
    skipped = [c for c in checks if c["status"] == STATUS_SKIP]

    if critical_fails:
        overall = "FAIL"
    elif warning_fails:
        overall = "PARTIAL"
    else:
        overall = "PASS"

    return {
        "checks": checks,
        "summary": {
            "total": len(checks),
            "passed": len(passes),
            "failed_critical": len(critical_fails),
            "failed_warning": len(warning_fails),
            "skipped": len(skipped),
        },
        "overall_status": overall,
        "errors": [c["detail"] for c in critical_fails],
        "warnings": [c["detail"] for c in warning_fails],
    }


def _check(
    check_id: str,
    description: str,
    passed: bool,
    severity: str,
    detail: str,
) -> dict[str, Any]:
    """Create a single check result dict."""
    return {
        "check_id": check_id,
        "description": description,
        "status": STATUS_PASS if passed else STATUS_FAIL,
        "severity": severity,
        "detail": detail,
    }
